"""Build the GamLog privacy pages from the app's own policy text.

The app bundles GamLog/Resources/privacy-{en,ko}.md (bp-log repo). This script turns
those files into gamlog/privacy/index.html and gamlog/privacy/ko/index.html, so the
in-app policy and the hosted one are the same words. tests/test_site.py fails if the
pages drift from the source (when the bp-log checkout sits next to this repo).

    python3 scripts/sync_privacy.py            # write the pages
    python3 scripts/sync_privacy.py --check    # exit 1 if they are out of date

When the policy text changes, update each page's "updated" line in PAGES and rerun.
"""
import html
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT.parent / "bp-log/GamLog/Resources"
EMAIL = "support@ongistudio.app"

PAGES = {
    "en": {
        "src": "privacy-en.md",
        "out": "gamlog/privacy/index.html",
        "placeholder": "[contact address to be added]",
        "contact": f'Email <a href="mailto:{EMAIL}">{EMAIL}</a>. GamLog is made by Ongi Studio.',
        "title": "GamLog Privacy Policy",
        "h1": "GamLog privacy policy",
        "updated": "Last updated: November 26, 2026",
        "description": "GamLog keeps your blood pressure notebook on your iPhone. No account, no server, no analytics, no advertising.",
        "url": "https://ongistudio.app/gamlog/privacy/",
        "other": ("/gamlog/privacy/ko/", "ko", "한국어"),
        "skip": "Skip to content",
        "nav": [("/gamlog/", "GamLog"), ("/support/", "Support")],
        "footer": "© 2026 Ongi Studio · No cookies, no analytics.",
    },
    "ko": {
        "src": "privacy-ko.md",
        "out": "gamlog/privacy/ko/index.html",
        "placeholder": "[문의처 추가 예정]",
        "contact": f'<a href="mailto:{EMAIL}">{EMAIL}</a> 으로 메일 주세요. 감록은 Ongi Studio(온기 스튜디오)가 만듭니다.',
        "title": "감록 개인정보 처리방침",
        "h1": "감록 개인정보 처리방침",
        "updated": "최종 수정일: 2026년 11월 26일",
        "description": "감록은 혈압 수첩을 iPhone 안에만 저장합니다. 회원가입, 서버, 분석 도구, 광고가 없습니다.",
        "url": "https://ongistudio.app/gamlog/privacy/ko/",
        "other": ("/gamlog/privacy/", "en", "English"),
        "skip": "본문으로 건너뛰기",
        "nav": [("/gamlog/ko/", "감록"), ("/support/#ko", "고객 지원")],
        "footer": "© 2026 Ongi Studio · 쿠키와 분석 도구를 쓰지 않아요.",
    },
}

LEAD = re.compile(r"^\*\*(?P<head>.+?)\*\*\s*(?P<body>.*)$", re.S)


def paragraphs(md: str) -> list[str]:
    """The policy's paragraphs, without the first line (the title and its draft note)."""
    blocks = [b.strip() for b in md.strip().split("\n\n") if b.strip()]
    return blocks[1:]


def render(lang: str, md: str) -> str:
    p = PAGES[lang]
    parts = []
    for block in paragraphs(md):
        m = LEAD.match(block)
        if m:
            head = m["head"].rstrip(".").strip()
            body = m["body"].strip()
            body_html = p["contact"] if body == p["placeholder"] else html.escape(body, quote=False)
            parts.append(f"    <h2>{html.escape(head, quote=False)}</h2>\n    <p>{body_html}</p>")
        else:
            parts.append(f"    <p>{html.escape(block, quote=False)}</p>")
    body = "\n".join(parts)
    other_href, other_lang, other_label = p["other"]
    nav = "\n".join(f'      <li><a href="{h}">{t}</a></li>' for h, t in p["nav"])
    return f"""<!doctype html>
<html lang="{lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{p["title"]}</title>
<meta name="description" content="{p["description"]}">
<link rel="canonical" href="{p["url"]}">
<link rel="alternate" hreflang="en" href="https://ongistudio.app/gamlog/privacy/">
<link rel="alternate" hreflang="ko" href="https://ongistudio.app/gamlog/privacy/ko/">
<link rel="icon" href="/assets/img/mark.svg" type="image/svg+xml">
<link rel="apple-touch-icon" href="/assets/img/apple-touch-icon.png">
<meta name="theme-color" content="#dce8e0" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#131b17" media="(prefers-color-scheme: dark)">
<link rel="stylesheet" href="/assets/css/site.css">
</head>
<body class="theme-gamlog">
<!-- Generated by scripts/sync_privacy.py from bp-log/GamLog/Resources/{p["src"]}. Edit the source, not this file. -->
<a class="skip" href="#main">{p["skip"]}</a>
<header class="site-header">
  <div class="wrap">
    <a class="brand" href="/" aria-label="Ongi Studio"><img src="/assets/img/mark.svg" alt="" width="36" height="36"><span class="brand-name" lang="en">Ongi Studio</span></a>
    <nav aria-label="Main"><ul class="nav">
{nav}
      <li><a class="lang-switch" href="{other_href}" lang="{other_lang}" hreflang="{other_lang}">{other_label}</a></li>
    </ul></nav>
  </div>
</header>

<main id="main" class="doc">
  <div class="narrow">
    <h1>{p["h1"]}</h1>
    <p class="updated">{p["updated"]}</p>
{body}
  </div>
</main>

<footer class="site-footer">
  <div class="wrap">
    <p>{p["footer"]}</p>
    <ul>
      <li><a href="/" lang="en">Ongi Studio</a></li>
{nav}
    </ul>
  </div>
</footer>
</body>
</html>
"""


def build(check: bool = False) -> list[str]:
    """Write (or, with check, compare) each page. Returns the pages that are out of date."""
    stale = []
    for lang, p in PAGES.items():
        src = SOURCE / p["src"]
        out = ROOT / p["out"]
        want = render(lang, src.read_text(encoding="utf-8"))
        have = out.read_text(encoding="utf-8") if out.exists() else ""
        if want != have:
            stale.append(p["out"])
            if not check:
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text(want, encoding="utf-8")
    return stale


if __name__ == "__main__":
    check = "--check" in sys.argv
    stale = build(check=check)
    if check and stale:
        sys.exit("out of date: " + ", ".join(stale) + " (run scripts/sync_privacy.py)")
    print("up to date" if not stale else "wrote " + ", ".join(stale))
